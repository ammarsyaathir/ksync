/* perf/gen-schema-members.mjs

   Injects the normalised `members` table (11th table) plus the baseline biodata
   for the artists declared inside database/hostinger_mysql_schema.sql, between
   two idempotent markers. Re-runnable: the previous block is replaced.

   The biodata is read straight out of the schema file's own `artists`.`members`
   JSON literals (a small SQL-literal parser handles MySQL escaping), so the
   generated table rows are guaranteed to be the same data the file already
   ships. Extraction is sanity-checked by counting "stage_name" keys in the raw
   literal, then the whole script is replayed against a SQLite mirror.

   Any difference against database/ksync.db is reported but not "fixed" -
   modifying the demo artists' biodata is a separate decision.
*/
import fs from 'node:fs';
import Database from 'better-sqlite3';
import { memberRow, MEMBER_COLUMNS, SQLITE_MEMBERS_DDL } from './members-util.mjs';

const SCHEMA = 'database/hostinger_mysql_schema.sql';
const OPEN = '-- >> GENERATED by perf/gen-schema-members.mjs - do not edit by hand >>';
const CLOSE = '-- << END GENERATED <<';
const CHECK_ONLY = process.argv.includes('--check');

// ---------- tiny SQL-literal parser (single-row VALUES tuples) ----------
function splitTuple(s, start) {
  const vals = [];
  let i = start + 1, cur = '', inStr = false, depth = 0;
  while (i < s.length) {
    const ch = s[i];
    if (inStr) {
      if (ch === '\\') { cur += ch + (s[i + 1] ?? ''); i += 2; continue; }
      if (ch === "'") {
        if (s[i + 1] === "'") { cur += "''"; i += 2; continue; }
        inStr = false; cur += ch; i++; continue;
      }
      cur += ch; i++; continue;
    }
    if (ch === "'") { inStr = true; cur += ch; i++; continue; }
    if (ch === '(') { depth++; cur += ch; i++; continue; }
    if (ch === ')') {
      if (depth === 0) { vals.push(cur.trim()); return { vals, end: i }; }
      depth--; cur += ch; i++; continue;
    }
    if (ch === ',' && depth === 0) { vals.push(cur.trim()); cur = ''; i++; continue; }
    cur += ch; i++;
  }
  throw new Error('unterminated VALUES tuple');
}

function unescapeSqlString(tok) {
  if (!(tok.startsWith("'") && tok.endsWith("'"))) return tok;
  const s = tok.slice(1, -1);
  let out = '';
  for (let i = 0; i < s.length; i++) {
    if (s[i] === '\\') {
      const n = s[i + 1]; i++;
      out += n === 'n' ? '\n' : n === 'r' ? '\r' : n === 't' ? '\t' : n === '0' ? '\0' : n;
    } else if (s[i] === "'" && s[i + 1] === "'") { out += "'"; i++; }
    else out += s[i];
  }
  return out;
}

// ---------- extract the artists straight out of the schema file ----------
const sqlText = fs.readFileSync(SCHEMA, 'utf8');
const artists = [];
const re = /INSERT INTO `artists` \(([^)]*)\) VALUES \(/g;
let m;
while ((m = re.exec(sqlText)) !== null) {
  const cols = m[1].split(',').map((c) => c.trim().replace(/`/g, ''));
  const { vals, end } = splitTuple(sqlText, m.index + m[0].length - 1);
  if (vals.length !== cols.length) throw new Error(`column/value mismatch for ${cols.join(',')}`);
  const raw = {};
  const row = {};
  cols.forEach((c, i) => { raw[c] = vals[i]; row[c] = unescapeSqlString(vals[i]); });
  if (!row.members) continue;

  // independent sanity check: does the parser agree with the raw text?
  const keyHits = (raw.members.match(/"stage_name"\s*:/g) || []).length;
  const parsed = JSON.parse(row.members);
  if (!Array.isArray(parsed)) throw new Error(`${row.name}: members JSON is not an array`);
  if (keyHits !== parsed.length) throw new Error(`${row.name}: parsed ${parsed.length} members but the literal has ${keyHits} stage_name keys - truncated!`);
  if (parsed.length === 0) continue;
  for (const p of parsed) if (!p.stage_name) throw new Error(`${row.name}: a member has no stage_name`);
  if (!Number.isInteger(Number(row.id))) throw new Error(`${row.name}: bad id`);

  artists.push({ id: Number(row.id), name: row.name, members: parsed });
}
if (artists.length === 0) throw new Error('no artists with biodata found - regex/format changed?');
console.log(`extracted ${artists.length} artists with biodata from ${SCHEMA}`);
for (const a of artists) console.log(`  #${a.id} ${a.name}: ${a.members.length} members (${a.members.map((x) => x.stage_name).join(', ')})`);

// ---------- informational diff against the local dev database ----------
try {
  const db = new Database(process.env.SQLITE_DB_PATH || 'database/ksync.db', { readonly: true });
  const diffs = [];
  for (const a of artists) {
    const local = db.prepare('SELECT id, members FROM artists WHERE id = ?').get(a.id);
    const localJson = local && local.members ? JSON.parse(local.members) : null;
    if (JSON.stringify(localJson) !== JSON.stringify(a.members)) {
      const sameSet = Array.isArray(localJson) && localJson.length === a.members.length
        && JSON.stringify(localJson.map((x) => x.stage_name).sort()) === JSON.stringify(a.members.map((x) => x.stage_name).sort());
      diffs.push(`  #${a.id} ${a.name}: schema has ${a.members.length} members, local DB has ${localJson ? localJson.length : 0}${sameSet ? ' (same members, different order)' : ''}`);
    }
  }
  console.log(diffs.length
    ? `NOTICE - these demo artists differ between the schema file and the local dev DB (left as-is):\n${diffs.join('\n')}`
    : 'local dev DB matches the schema file for all demo artists');
  db.close();
} catch (e) { console.log(`(skipped local DB comparison: ${e.message})`); }

// ---------- build the generated block ----------
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);
const INSERT_COLS = MEMBER_COLUMNS.filter((c) => c !== 'is_active'); // is_active keeps its DEFAULT 1
const COLS = `(\`artist_id\`,${INSERT_COLS.map((c) => '`' + c + '`').join(',')})`;

const lines = [OPEN,
  '-- Normalised idol biodata: the 11th table, one row per member of the artists above.',
  '-- Regenerate with: node perf/gen-schema-members.mjs',
  'DROP TABLE IF EXISTS `members`;',
  'CREATE TABLE `members` (',
  '  `id` INT AUTO_INCREMENT PRIMARY KEY,',
  '  `artist_id` INT NOT NULL,',
  '  `stage_name` VARCHAR(100) NOT NULL,',
  '  `birth_name` VARCHAR(150) DEFAULT NULL,',
  '  `group_name` VARCHAR(100) DEFAULT NULL,',
  '  `position` VARCHAR(200) DEFAULT NULL,',
  '  `dob` DATE DEFAULT NULL,',
  '  `zodiac` VARCHAR(20) DEFAULT NULL,',
  '  `height_cm` DECIMAL(5,1) DEFAULT NULL,',
  '  `blood_type` VARCHAR(5) DEFAULT NULL,',
  '  `mbti` VARCHAR(20) DEFAULT NULL,',
  '  `nationality` VARCHAR(50) DEFAULT NULL,',
  '  `debut_year` INT DEFAULT NULL,',
  '  `photo` VARCHAR(255) DEFAULT NULL,',
  '  `is_active` TINYINT(1) NOT NULL DEFAULT 1,',
  '  `sort_order` INT NOT NULL DEFAULT 0,',
  '  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,',
  '  UNIQUE KEY `uniq_members_artist_stage` (`artist_id`, `stage_name`),',
  '  KEY `idx_members_artist` (`artist_id`),',
  '  CONSTRAINT `fk_members_artist` FOREIGN KEY (`artist_id`) REFERENCES `artists` (`id`) ON DELETE CASCADE ON UPDATE CASCADE',
  ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;',
  ''];
const statements = [];
let rows = 0;
for (const a of artists) {
  a.members.forEach((mem, i) => {
    const r = memberRow(mem, i + 1);
    const vals = [q(r.stage_name), q(r.birth_name), q(r.group_name), q(r.position), q(r.dob), q(r.zodiac),
      r.height_cm === null ? 'NULL' : String(r.height_cm), q(r.blood_type), q(r.mbti), q(r.nationality),
      r.debut_year === null ? 'NULL' : String(r.debut_year), q(r.photo), r.sort_order];
    statements.push(`INSERT IGNORE INTO \`members\` ${COLS}\nSELECT \`id\`, ${vals.join(', ')} FROM \`artists\` WHERE \`name\` = ${q(a.name)};`);
    rows++;
  });
}
lines.push(...statements);
lines.push(CLOSE);
const block = lines.join('\n');

// replay against a SQLite mirror: create the artists, then run the block
{
  const mirror = new Database(':memory:');
  mirror.pragma('foreign_keys = ON');
  mirror.exec('CREATE TABLE artists (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL UNIQUE);');
  const insA = mirror.prepare('INSERT INTO artists (id, name) VALUES (?, ?)');
  for (const a of artists) insA.run(a.id, a.name);
  mirror.exec(SQLITE_MEMBERS_DDL);
  let failed = 0;
  for (const st of statements) {
    try { mirror.exec(st.replace(/INSERT\s+IGNORE\s+INTO/gi, 'INSERT OR IGNORE INTO')); } catch (e) { failed++; console.log(`  replay FAIL (${e.message}): ${st.slice(0, 80)}`); }
  }
  const n = mirror.prepare('SELECT COUNT(*) c FROM members').get().c;
  const after = (() => { for (const st of statements) mirror.exec(st.replace(/INSERT\s+IGNORE\s+INTO/gi, 'INSERT OR IGNORE INTO')); return mirror.prepare('SELECT COUNT(*) c FROM members').get().c; })();
  const orph = mirror.prepare('SELECT COUNT(*) c FROM members m LEFT JOIN artists a ON a.id = m.artist_id WHERE a.id IS NULL').get().c;
  const fk = mirror.pragma('foreign_key_check').length;
  console.log(`replay check: statements=${statements.length} failed=${failed} rows=${n} rowsAfterSecondRun=${after} orphans=${orph} fkViolations=${fk}`);
  if (failed || n !== rows || after !== rows || orph !== 0 || fk !== 0) throw new Error('mirror replay failed');
  mirror.close();
}

// ---------- splice it in, right before the event_categories section ----------
const anchor = '-- 4. Table structure for `event_categories`';
const anchorIdx = sqlText.indexOf(anchor);
if (anchorIdx === -1) throw new Error('anchor not found');
const anchorLineStart = sqlText.lastIndexOf('-- --------------------------------------------------------', anchorIdx);

const openIdx = sqlText.indexOf(OPEN);
const closeIdx = sqlText.indexOf(CLOSE);
if (CHECK_ONLY) {
  console.log(openIdx !== -1 ? 'block already present' : 'block not present yet');
  process.exit(0);
}
let next;
if (openIdx !== -1 && closeIdx !== -1) {
  next = sqlText.slice(0, openIdx).replace(/\s+$/, '') + '\n\n' + block + '\n\n' + sqlText.slice(closeIdx + CLOSE.length).replace(/^\s+/, '');
} else {
  next = sqlText.slice(0, anchorLineStart).replace(/\s+$/, '') + '\n\n' + block + '\n\n' + sqlText.slice(anchorLineStart);
}
fs.writeFileSync(SCHEMA, next, 'utf8');

console.log(`\ninjected: members DDL + ${rows} member rows for ${artists.length} artists`);
console.log(`schema now: ${next.split('\n').length} lines, ${next.length} chars`);
console.log(`markers: open=${(next.match(/GENERATED by perf\/gen-schema-members\.mjs/g) || []).length} close=${(next.match(/END GENERATED/g) || []).length}`);
console.log(`stats: CREATE TABLE members=${(next.match(/CREATE TABLE `members`/g) || []).length}, INSERT IGNORE INTO members=${(next.match(/INSERT IGNORE INTO `members`/g) || []).length}`);
